import MetaTrader5 as mt5
import pandas as pd
import json
import time
from datetime import datetime
import os
from dotenv import load_dotenv
from langchain_groq import ChatGroq
import re

dotenv_path = os.path.join(os.path.dirname(__file__), '.env')
load_dotenv(dotenv_path, override=True)

API_KEY = os.getenv("GROQ_API_KEY")

TRADING_PROMPT = """You are a high-frequency directional volume scalper for XAUUSD. You analyze the compressed market snapshot and output ONLY a valid JSON object. No explanations. No markdown. No extra text.

=== DIRECTIONAL SCALPING STRATEGY ===
1. TREND IDENTIFICATION: Your ONLY job is to determine the general market direction based on the recent price action.
2. EXECUTION: 
   - If the macro trend is UP (Bullish), signal "BUY".
   - If the macro trend is DOWN (Bearish), signal "SELL".
   - Only output "HOLD" if the market is completely flat, chaotic, or lacks any clear direction.
3. Rapid fire scalping is expected. Always trade in the direction of the underlying trend.

=== OUTPUT FORMAT (STRICT) ===
Return ONLY this JSON, no markdown, no prose:
{
  "thoughts":   "1 sentence: Identify the trend direction and momentum.",
  "signal":     "BUY",
  "reason":     "if HOLD, 1 sentence why; else empty string",
  "confidence": 0.85
}  
IMPORTANT:
- signal: MUST be "BUY", "SELL", or "HOLD"
- confidence: must be >= 0.85 for BUY/SELL

=== MARKET SNAPSHOT ===
{market_snapshot}
"""

def write_state(thoughts, action, confidence):
    state = {
        "timestamp": datetime.now().isoformat(),
        "ai": {
            "thought": thoughts,
            "signal": action,
            "confidence": confidence
        }
    }
    with open("shared_state.json", "w") as f:
        json.dump(state, f, indent=2)

def get_snapshot():
    rates = mt5.copy_rates_from_pos("XAUUSD", mt5.TIMEFRAME_M15, 0, 10)
    if rates is None or len(rates) == 0:
        return "No data"
    df = pd.DataFrame(rates)
    df['time'] = pd.to_datetime(df['time'], unit='s')
    return df.tail(5).to_string()

def execute_trade(action, price):
    # Hardcoded $4 SL, $2 TP for tight volume scalping
    sl_distance = 4.0
    tp_distance = 2.0
    
    sl = price - sl_distance if action == "BUY" else price + sl_distance
    tp = price + tp_distance if action == "BUY" else price - tp_distance
    
    order_type = mt5.ORDER_TYPE_BUY if action == "BUY" else mt5.ORDER_TYPE_SELL
    
    request = {
        "action": mt5.TRADE_ACTION_DEAL,
        "symbol": "XAUUSD",
        "volume": 0.01,
        "type": order_type,
        "price": price,
        "sl": sl,
        "tp": tp,
        "deviation": 20,
        "magic": 123456,
        "comment": "AI Scalper",
        "type_time": mt5.ORDER_TIME_GTC,
        "type_filling": mt5.ORDER_FILLING_IOC,
    }
    
    result = mt5.order_send(request)
    if result and result.retcode == mt5.TRADE_RETCODE_DONE:
        print(f"Trade executed: {result.order}")
        return result.order
    else:
        print(f"Trade failed: {result}")
        return None

def main():
    if not API_KEY or API_KEY == "your_groq_api_key_here":
        print("Please set your GROQ_API_KEY in the .env file.")
        write_state("Bot stopped: GROQ_API_KEY not found in .env", "HOLD", 0.0)
        return

    if not mt5.initialize():
        print("MT5 initialize() failed")
        write_state("Bot stopped: MT5 not found or failed to connect", "HOLD", 0.0)
        return

    llm = ChatGroq(model="deepseek-r1-distill-llama-70b", temperature=0.2, groq_api_key=API_KEY)
    
    print("Bot started. Monitoring XAUUSD...")
    write_state("Bot initialized and connected to MT5. Starting scan...", "SCANNING", 0.0)
    
    while True:
        positions = mt5.positions_get(symbol="XAUUSD")
        if positions is not None and len(positions) > 0:
            write_state(f"Open trade #{positions[0].ticket} running. Waiting for quick TP/SL hit...", "HOLD", 0.0)
            time.sleep(5)
            continue
            
        snapshot = get_snapshot()
        prompt = TRADING_PROMPT.format(market_snapshot=snapshot)
        
        try:
            write_state("Analyzing M15 market snapshot for directional scalp...", "SCANNING", 0.0)
            response = llm.invoke(prompt)
            content = response.content
            
            # Strip <think> blocks generated by Deepseek R1
            content = re.sub(r'<think>.*?</think>', '', content, flags=re.DOTALL)
            
            # Extract JSON block
            if "{" in content and "}" in content:
                json_str = content[content.find("{"):content.rfind("}")+1]
                data = json.loads(json_str)
                signal = data.get("signal", "HOLD")
                confidence = data.get("confidence", 0.0)
                thoughts = data.get("thoughts", "")
                
                write_state(f"AI Decision: {thoughts}", signal, confidence)
                
                if signal in ["BUY", "SELL"] and confidence >= 0.85:
                    tick = mt5.symbol_info_tick("XAUUSD")
                    if tick:
                        price = tick.ask if signal == "BUY" else tick.bid
                        ticket = execute_trade(signal, price)
                        if ticket:
                            time.sleep(3) # Wait for MT5 server to sync the active ticket
                else:
                    time.sleep(5)
            else:
                write_state("Failed to parse JSON from AI", "ERROR", 0.0)
                time.sleep(5)
                
        except Exception as e:
            print(f"Error: {e}")
            write_state(f"Error during AI call: {str(e)[:50]}...", "ERROR", 0.0)
            time.sleep(5)

if __name__ == "__main__":
    main()
