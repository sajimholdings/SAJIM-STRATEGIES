REQUEST_ID_RE = re.compile(r"^[A-Za-z0-9_-]{8,64}$")    # == modal_runner.SAFE_REQUEST_ID
REQUEST_KINDS: Tuple[str, ...] = ("check", "dev", "holdout", "finalize")


def derive_request_id(family: str, code_sha256: str, kind: str) -> str:
    """Deterministic dedup id for dev/holdout/finalize (32 hex). Checks use uuid4().hex."""
    if kind not in REQUEST_KINDS:
        raise ValueError(f"unknown request kind {kind!r}")
    blob = f"sajim.lab.req/1|{_family(family)}|{code_sha256}|{kind}".encode("ascii")
    return hashlib.sha256(blob).hexdigest()[:32]


