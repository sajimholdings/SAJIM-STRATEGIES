_FAMILY_RE = re.compile(gates.LAB_ID_PATTERN)
_SHA_RE = re.compile(r"^[0-9a-f]{64}$")
SLOT_KEY_PATTERN = (r"^(?:(?:trial|holdout_touch):lab_[a-z0-9_]{3,40}:[1-9]"
                    r"|holdout_sha:[0-9a-f]{64})$")
_SLOT_RE = re.compile(SLOT_KEY_PATTERN)


def _family(family: str) -> str:
    if not _FAMILY_RE.fullmatch(family or ""):
        raise ValueError(f"family {family!r} must match {gates.LAB_ID_PATTERN}")
    return family


def trial_key(family: str, n: int) -> str:
    return f"trial:{_family(family)}:{int(n)}"


def holdout_touch_key(family: str, n: int) -> str:
    return f"holdout_touch:{_family(family)}:{int(n)}"


def holdout_sha_key(code_sha256: str) -> str:
    if not _SHA_RE.fullmatch(code_sha256 or ""):
        raise ValueError("code_sha256 must be 64 lowercase hex chars")
    return f"holdout_sha:{code_sha256}"


def slot_filename(key: str) -> str:
    """Windows-safe file name for a slot key (':' is illegal in NTFS names)."""
    if not _SLOT_RE.fullmatch(key):
        raise ValueError(f"bad slot key {key!r}")
    return key.replace(":", "__") + ".json"


def utc_stamp(when: Optional[datetime] = None) -> str:
    """Sortable UTC stamp for ledger file names: 20261012T221530123456Z."""
    t = (when or datetime.now(timezone.utc)).astimezone(timezone.utc)
    return t.strftime("%Y%m%dT%H%M%S") + f"{t.microsecond:06d}Z"


def ledger_filename(stamp: str, request_id: str, record_type: str) -> str:
    if record_type not in RECORD_TYPES:
        raise ValueError(f"unknown record_type {record_type!r}")
    if not REQUEST_ID_RE.fullmatch(request_id):
        raise ValueError(f"bad request_id {request_id!r}")
    return f"{stamp}_{request_id}_{record_type}.json"


