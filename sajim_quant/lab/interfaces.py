class LabError(Exception):
    """Base for refusals that map 1:1 to an HTTP status on the lab API."""

    status: int = 400
    code: str = "bad_request"

    def __init__(self, message: str, *, code: Optional[str] = None, reasons: Sequence[str] = ()):
        super().__init__(message)
        if code:
            self.code = code
        self.reasons: Tuple[str, ...] = tuple(reasons)

    def detail(self) -> Dict[str, Any]:
        return {"code": self.code, "message": str(self), "reasons": list(self.reasons)}


