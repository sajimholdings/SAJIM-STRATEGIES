@dataclass(frozen=True)
class ScrambleSpec:
    """Rows [start, n) replaced by the frozen shuffled-bar random walk (start >= 1)."""

    start: int
    seed: int


@dataclass(frozen=True)
class SandboxRun:
    """One generate_signals call. cut = frame prefix length; scramble = future replacement."""

    run_id: str
    params: Mapping[str, Number]
    cut: Optional[int] = None
    scramble: Optional[ScrambleSpec] = None

    def __post_init__(self):
        if not _RUN_ID_RE.fullmatch(self.run_id):
            raise ValueError(f"run_id {self.run_id!r} must match {RUN_ID_PATTERN}")
        if self.cut is not None and self.scramble is not None:
            raise ValueError("a run has a cut or a scramble, not both")
        if self.cut is not None and self.cut < 1:
            raise ValueError("cut must be >= 1")
        if self.scramble is not None and self.scramble.start < 1:
            raise ValueError("scramble.start must be >= 1")

    def n_bars(self, frame_bars: int) -> int:
        """Length of the frame this run's strategy sees (bars in its events are < this)."""
        return self.cut if self.cut is not None else frame_bars


@dataclass(frozen=True)
class SandboxJob:
    """Everything one sandbox needs. Bytes only; the executor never interprets them."""

    frame_parquet: bytes
    n_bars: int
    strategy_py: bytes
    indicators_py: bytes
    runs: Tuple[SandboxRun, ...]
    allow_short: bool
    per_run_timeout_s: float = PER_RUN_TIMEOUT_S
    job_timeout_s: float = JOB_TIMEOUT_S
    label: str = ""                      # e.g. "check" / "neighbours"; logs only

    def __post_init__(self):
        if not 1 <= len(self.runs) <= MAX_RUNS_PER_JOB:
            raise ValueError(f"1..{MAX_RUNS_PER_JOB} runs per job, got {len(self.runs)}")
        ids = [r.run_id for r in self.runs]
        if len(set(ids)) != len(ids):
            raise ValueError("duplicate run_id in job")
        if not 1 <= self.n_bars <= MAX_FRAME_BARS:
            raise ValueError(f"n_bars must be 1..{MAX_FRAME_BARS}")
        if len(self.frame_parquet) > MAX_FRAME_BYTES:
            raise ValueError("frame too large for a sandbox job")
        if len(self.strategy_py) > gates.MAX_SOURCE_BYTES:
            raise ValueError("strategy source too large")


