@dataclass(frozen=True)
class DecodedJob:
    """Trusted view of a SandboxResult after sandbox_io.decode_result()."""

    events: Mapping[str, np.ndarray]      # run_id -> validated EVENTS_DTYPE array (ok runs only)
    errors: Tuple[RunError, ...]
    timings: Mapping[str, float]
    versions: Mapping[str, str]
    sensitive_env_names: Tuple[str, ...]  # names (never values) of SAJIM_/MODAL_/ANTHROPIC_/CLAUDE_ vars seen

    def ok(self, run_id: str) -> bool:
        return run_id in self.events and not any(e.run_id == run_id for e in self.errors)

    @property
    def job_ok(self) -> bool:
        return not any(e.run_id is None for e in self.errors)


